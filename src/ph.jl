# Particle-hole (PH) half construction of the segment spaces (v0.1.17; from the Tcc_ph branch, 4ad2e3a).
#
# One 2-flavour segment has 2N orbitals.  The map
#     P c†_{m,f} P⁻¹ = (-1)^(s-m) ε_f c_{-m,f̄},   P|0> = |full>,   (FuzzifiED ordering "asc")
# commutes with Lz, L±, the flavour SU(2) (Casimir and Sz -> -Sz), maps the segment particle number
# ne -> 2N - ne, sends the single-segment interaction to itself up to a constant, and every density /
# pairing mode to a multiple of a mode of the same kind (Tcc_ph ph_check.jl, N = 4..8, residual
# < 1e-10).  Hence every (C2, l) multiplet of sector 2N - ne is the P-image of one of sector ne.
# Because the multiplicity basis returned by eigen() is arbitrary anyway, the sectors ne > N are
# *defined* here as the P-images of the stored sectors ne < N; only ne <= N is diagonalised.
#
# The resulting segment spaces span exactly the same multiplet subspaces as a direct build (gauge-
# invariant projectors agree), so every physical number (spectrum, C2, |matrix elements|, KK, OPE)
# agrees; individual vectors differ by the usual multiplet gauge, so a PH-built basis is a different
# basis (its own SHA) and is never mixed with checkpoints of a directly built one.
#
# Gain (segment spaces are built in the flavour-Sz = 0 sector, so ne is even):
#   odd N : no ne = N sector -> exactly half is diagonalised and stored (N9, N11: 50 %);
#   even N: the self-conjugate ne = N sector cannot be halved and dominates (N10: 73 %, N12 71.6 %).
#   Build time (cluster, 64 physical cores, v0.1.17 t13, BLAS 1; with BLAS 16 the N11 PH build is 52.8 s, B20): N9 3.6 -> 1.0 s, N10 12.1 -> 7.7 s,
#   N11 242 -> 121 s (2.0x); the direct timings include first-call compilation (Tcc_ph branch,
#   compiled: N10 10.0 -> 11.2 s, N11 246 -> 128 s).  The PH-built spaces are not slower to use
#   (18-block spectrum: N9 59 vs 46 s, N10 330 vs 304 s, direct vs PH).
# Default: on when the largest segment sector has >= 2000 configurations (basis.ph_half = "auto",
# src/resources.jl; that is N >= 10); below that the build takes seconds and the
# frozen N <= 9 results keep their directly built bases.  Existing segment_spaces.ckpt are never
# rebuilt; meta.ph_half / manifest info.ph_half record which construction was used.
#
# Validation (test/t13_ph.jl, PH vs direct build, all PASS):
#   N4-N8: full pipeline basis->...->summary with ph_half true vs false: KK projected states
#          (134/233/290/296/298) and OPE equal (<= 3.4e-14);
#   N4-N7, N9, N10: 18-block spectrum dE <= 2.7e-13, dC2 <= 5.8e-12; KK/Gamma2 edges <= 2.0e-13;
#   N11: 5 blocks incl. (1,1) L1 (D 1.0e7), 108 states dE 1.5e-13, dC2 3.6e-13; edges 3.9e-14;
#   N4-N12: same multiplet subspaces, B = A U with U orthogonal: |U'U-I| <= 1.3e-12,
#           |B-AU| <= 4.4e-12, L+ images with the same U <= 2.9e-11 (N12 against the frozen basis).
#   Earlier (Tcc_ph ph_check.jl): P maps H_seg, densities, pairings covariantly for N4-N8 (< 1e-10).

ph_partner(lz2, fl) = [only(findall(p -> lz2[p] == -lz2[o] && fl[p] == -fl[o], eachindex(lz2))) for o in eachindex(lz2)]
ph_eta(nm, lz2, fl) = [Float64((-1)^round(Int, (nm - 1) / 2 - lz2[o] / 2) * (fl[o] > 0 ? 1 : -1)) for o in eachindex(lz2)]
_ph_before(conf, o) = count_ones(conf & ((1 << (o - 1)) - 1))        # FuzzifiED ordering "asc"

"""Signed permutation P from basis `bs` (ne) to basis `bsf` (no - ne)."""
function ph_matrix(bs, bsf, partner, eta)
    no = length(partner); full = (1 << no) - 1
    idx = Dict(c => i for (i, c) in enumerate(bsf.cfs.conf))
    I = Vector{Int}(undef, bs.dim); V = Vector{Float64}(undef, bs.dim)
    Threads.@threads for j in 1:bs.dim
        conf = bs.cfs.conf[j]; c = full; sg = 1.0
        for o in no:-1:1                      # c_{obar1} ... c_{obark}|full>, rightmost first
            (conf >> (o - 1)) & 1 == 1 || continue
            p = partner[o]
            sg *= (-1)^_ph_before(c, p) * eta[o]; c &= ~(1 << (p - 1))
        end
        I[j] = idx[c]; V[j] = sg
    end
    sparse(I, collect(1:bs.dim), V, bsf.dim, bs.dim)
end

"""Diagonalise only the sectors ne <= N (frozen setup otherwise unchanged)."""
function ph_build_half(nm::Int, setup=segment_setup(nm))
    sec = setup.sec_pt
    keep = [i for i in axes(sec, 2) if sec[1, i] <= nm]
    sp = BuildSegSpaces(2nm, sec[:, keep], setup.qnd_pt, setup.tms_lzlp_pt, setup.tms_c2, setup.c2_rng)
    (nm=nm, sec=sec, keep=keep, spaces=collect(sp))
end

"""Full segment spaces (sector order of `setup.sec_pt`) with ne > N generated by P."""
function ph_expand(h, setup=segment_setup(h.nm))
    nm = h.nm; no = 2nm; qnd = setup.qnd_pt
    lz2 = qnd[2].charge; fl = qnd[3].charge
    partner = ph_partner(lz2, fl); eta = ph_eta(nm, lz2, fl)
    nsec = size(h.sec, 2); pos = Dict(h.sec[1, i] => k for (k, i) in enumerate(h.keep))
    src = h.spaces[1]
    bs = Vector{Basis}(undef, nsec); bs1 = Vector{Basis}(undef, nsec)
    Pm = Vector{Any}(undef, nsec); Pm1 = Vector{Any}(undef, nsec)
    for i in 1:nsec
        ne = h.sec[1, i]
        if ne <= nm
            k = pos[ne]; bs[i] = src.bs[k]; isassigned(src.bs1, k) && (bs1[i] = src.bs1[k])
        else
            k = pos[no-ne]; seci = h.sec[:, i]
            bs[i] = Basis(Confs(no, seci, qnd; disp_std=false))
            Pm[i] = ph_matrix(src.bs[k], bs[i], partner, eta)
            if seci[2] == 0
                s1 = copy(seci); s1[2] = 2
                bs1[i] = Basis(Confs(no, s1, qnd; disp_std=false))
                Pm1[i] = ph_matrix(src.bs1[k], bs1[i], partner, eta)
            end
        end
    end
    out = Any[]
    for sp in h.spaces
        T = eltype(sp.sts[1])
        l_rng = Vector{Vector{Int}}(undef, nsec); l_lookup = Vector{Dict{Int,Int}}(undef, nsec)
        ptr = Vector{Vector{Int}}(undef, nsec)
        sts = Vector{Matrix{T}}(undef, nsec); sts1 = Vector{Matrix{T}}(undef, nsec)
        for i in 1:nsec
            ne = h.sec[1, i]; k = pos[min(ne, no - ne)]
            l_rng[i] = copy(sp.l_rng[k]); l_lookup[i] = copy(sp.l_lookup[k])
            ptr[i] = sp.ptr_st[k] .- (sp.ptr_st[k][1] - 1)            # local pointers 1..
            if ne <= nm
                sts[i] = sp.sts[k]; isassigned(sp.sts1, k) && (sts1[i] = sp.sts1[k])
            else
                sts[i] = Matrix{T}(Pm[i] * sp.sts[k])
                isassigned(sp.sts1, k) && (sts1[i] = Matrix{T}(Pm1[i] * sp.sts1[k]))
            end
        end
        off = 0
        for i in 1:nsec                                               # global pointers as BuildSegSpace
            ptr[i] = ptr[i] .+ off; off = ptr[i][end] - 1
        end
        push!(out, SegSpace{T}(h.sec, copy(sp.sec_modul), l_rng, l_lookup, ptr, bs, bs1, sts, sts1))
    end
    out
end

